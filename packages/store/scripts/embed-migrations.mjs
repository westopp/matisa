// Regenerates src/migrations/migrations.embedded.ts from ../migrations/*.sql.
//
// The engine ships as a single bundled file, so migrations cannot be read off
// disk relative to import.meta.url at runtime — they are embedded as strings.
// The .sql files stay the thing you author; run this after adding one:
//
//   node packages/store/scripts/embed-migrations.mjs
//
// Only files registered in the LEDGER below are embedded.
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const migrationsDir = join(here, "..", "migrations")
const out = join(here, "..", "src", "migrations", "migrations.embedded.ts")

const LEDGER = [
  { version: "0001_init", file: "0001_init.sql" },
  { version: "0002_project_icons", file: "0002_project_icons.sql" },
  // Registered on the exposure branch: command vars stopped being context-scoped
  // in code long before the column went, and nothing has read context_id since.
  { version: "0003_command_vars_unscoped", file: "0003_command_vars_unscoped.sql" },
  { version: "0004_crash_kind", file: "0004_crash_kind.sql" },
  { version: "0005_events_unscoped", file: "0005_events_unscoped.sql" },
  // Environments stop being global: every context names its project, every
  // project owns its own `base`, and the always-injected global layer is gone.
  { version: "0006_env_project_scoped", file: "0006_env_project_scoped.sql" }
]

const entries = LEDGER.map(({ version, file }) => {
  const sql = readFileSync(join(migrationsDir, file), "utf8")
  return `  {\n    version: ${JSON.stringify(version)},\n    sql: ${JSON.stringify(sql)}\n  }`
})

writeFileSync(
  out,
  `// GENERATED by scripts/embed-migrations.mjs — do not edit by hand.
// Author migrations as .sql files in packages/store/migrations, register them
// in the script's LEDGER, and re-run it. Embedded so the bundled engine needs
// no migrations directory on disk.

export interface EmbeddedMigration {
  readonly version: string
  readonly sql: string
}

export const MIGRATIONS: ReadonlyArray<EmbeddedMigration> = [
${entries.join(",\n")}
]
`
)

console.log(`wrote ${out} (${LEDGER.length} migrations)`)
