import Foundation

/// Builds a Caddyfile from the URL-bearing entries in the config. The output
/// matches the user's existing style: a top `auto_https off` block, then one
/// `http://<url>` reverse_proxy block per declared URL.
enum CaddyfileGenerator {
    static func render(from config: AppConfig) -> String {
        var blocks: [String] = []
        blocks.append("# Generated by Matisa. Edits will be overwritten.\n# Source: ~/.config/matisa/services.ts\n")
        blocks.append("{\n\tauto_https off\n}\n")

        for spec in config.services {
            for entry in spec.exposedPorts {
                guard let url = entry.url else { continue }
                blocks.append("http://\(url) {\n\treverse_proxy localhost:\(entry.port)\n}\n")
            }
        }

        return blocks.joined(separator: "\n")
    }

    /// Write the rendered Caddyfile to the configured location, returning the
    /// destination URL. Does nothing if `config.caddyfile` is nil.
    @discardableResult
    static func write(_ config: AppConfig) throws -> URL? {
        guard let dest = config.caddyfile else { return nil }
        let rendered = render(from: config)
        try rendered.write(to: dest, atomically: true, encoding: .utf8)
        return dest
    }
}
