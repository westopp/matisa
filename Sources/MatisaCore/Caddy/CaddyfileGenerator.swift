import Foundation

/// Builds a Caddyfile from the URL-bearing entries in the config plus any
/// runtime same-network exposures. The output matches the user's existing
/// style: a top `auto_https off` block, then one `http://<url>` reverse_proxy
/// block per declared URL, then an extra block per active `<service>.matisa.local`
/// exposure pointing at the same upstream.
///
/// Shared by the app and the engine via MatisaCore — the engine renders the
/// canonical file when exposures change, and the app reuses the same renderer
/// in its local-fallback path.
public enum CaddyfileGenerator {
    /// `exposures` maps service id → exposure state. Same-network blocks are
    /// emitted only for entries whose `sameNetwork` status carries a hostname
    /// (i.e. `.advertising` or `.active`).
    public static func render(
        from config: AppConfig,
        services: [Service] = [],
        exposures: [String: ServiceExposure] = [:]
    ) -> String {
        var blocks: [String] = []
        blocks.append("# Generated by Matisa. Edits will be overwritten.\n# Source: ~/.config/matisa/services.ts\n")
        blocks.append("{\n\tauto_https off\n}\n")

        for spec in config.services {
            for entry in spec.exposedPorts {
                guard let url = entry.url else { continue }
                blocks.append("http://\(url) {\n\treverse_proxy localhost:\(entry.port)\n}\n")
            }
        }

        // Runtime same-network blocks. Each maps `<hostname>` → the same upstream
        // port the service's primary URL would route to. We pick the first
        // exposed port from the spec since same-network mirrors the canonical
        // local entry rather than fanning out per port.
        for service in services {
            guard let exposure = exposures[service.id],
                  let hostname = exposure.sameNetwork.hostname,
                  let port = service.spec.exposedPorts.first?.port else { continue }
            blocks.append("http://\(hostname) {\n\treverse_proxy localhost:\(port)\n}\n")
        }

        return blocks.joined(separator: "\n")
    }

    /// Write the rendered Caddyfile to the configured location, returning the
    /// destination URL. Does nothing if `config.caddyfile` is nil.
    @discardableResult
    public static func write(
        _ config: AppConfig,
        services: [Service] = [],
        exposures: [String: ServiceExposure] = [:]
    ) throws -> URL? {
        guard let dest = config.caddyfile else { return nil }
        let rendered = render(from: config, services: services, exposures: exposures)
        try rendered.write(to: dest, atomically: true, encoding: .utf8)
        return dest
    }
}
